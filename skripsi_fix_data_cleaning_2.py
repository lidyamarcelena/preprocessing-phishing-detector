import pandas as pd

file_path = "/content/new_dataset_legitimate_5.csv"
df = pd.read_csv(file_path)

# jumlah data awal
print("Jumlah total data:", len(df))

# pencarian url duplikat
duplicates = df[df.duplicated(subset=['url'], keep=False)]
duplicates = duplicates.sort_values(by='url')

# tampilkan url yang sama
print("\nDaftar URL yang sama:")
print(duplicates[['url']])

# jumlah baris yang duplikat
print("\nTotal baris yang memiliki URL sama:", len(duplicates))

# jumlah URL yang terduplikasi
print("Jumlah URL berbeda yang terduplikasi:", duplicates['url'].nunique())