import pandas as pd

file_path = "/content/new_dataset_legitimate_6.csv"
df = pd.read_csv(file_path)

print("jumlah dataset sebelum hapus duplikasi:", len(df))

df_clean = df.drop_duplicates(subset=['url'])

print("jumlah dataset setelah hapus duplikasi:", len(df_clean))

"""menyimpan"""

output_path = "/content/new_dataset_legitimate_6.csv"
df_clean.to_csv(output_path, index=False)

print("done", output_path)

